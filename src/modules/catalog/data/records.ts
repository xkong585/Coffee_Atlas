/**
 * The Coffee Atlas catalog: every country, region, bean, drink, pairing and
 * source the app serves. Member 3 (catalog) owns this file.
 *
 * Seeded from the sourced records Member 2 compiled for the map preview (all
 * accessed 2026-10-16). Each record is a short, conservative summary of the
 * cited public pages. To change content, edit this file and run
 * `npm run catalog:check`, which validates every record against the shared
 * contract and checks referential integrity (see ../lib/integrity.ts).
 *
 * Modelling rules (see docs/CONTRACTS.md):
 * - Bean origin is where the coffee grows. Drink associations are cultural
 *   and do not imply bean origin: Türkiye and Italy have drinks but no beans.
 * - Exactly one region (Java) has `center: null`, so it is list-only.
 * - Kenya AA is recorded at country level (`regionId: null`): AA is a size
 *   grade, not a place.
 * - "documented" pairings are traditions the cited sources describe; every
 *   other pairing is labeled "suggested".
 * - Unknown values stay explicit: `null` descriptions and empty arrays.
 * - Country `isoCode` must equal `iso` in public/map/countries.geojson.
 */
import "server-only";
import type { CatalogSnapshot } from "@/contracts";

type Source = CatalogSnapshot["sources"][number];

const ACCESSED_AT = "2026-10-16";

function source(id: string, title: string, url: string, publisher: string): Source {
  return { id, title, url, publisher, accessedAt: ACCESSED_AT };
}

